-- Customer accounts, categories, reviews, wishlist and shipping details.
-- Make yourself admin afterwards with: python make_admin.py you@example.com

-- ---------- Accounts ----------

create table if not exists users (
    id            bigint generated by default as identity primary key,
    name          text        not null,
    email         text        not null,
    password_hash text        not null,
    role          text        not null default 'customer' check (role in ('customer', 'admin')),
    phone         text        not null default '',   -- last shipping details, prefill checkout
    address       text        not null default '',
    created_at    timestamptz not null default now()
);

create unique index if not exists users_email_key on users (lower(email));

-- ---------- Categories ----------

create table if not exists categories (
    id         bigint generated by default as identity primary key,
    name       text        not null,
    created_at timestamptz not null default now()
);

create unique index if not exists categories_name_key on categories (lower(name));

alter table products
    add column if not exists category_id bigint references categories (id) on delete set null;

-- ---------- Orders: owner and shipping details ----------

alter table orders
    add column if not exists user_id bigint references users (id) on delete set null,
    add column if not exists phone   text not null default '',
    add column if not exists address text not null default '',
    add column if not exists note    text not null default '';

create index if not exists orders_user_id_idx on orders (user_id);

-- ---------- Reviews (one per customer per product) ----------

create table if not exists reviews (
    id         bigint generated by default as identity primary key,
    product_id bigint      not null references products (id) on delete cascade,
    user_id    bigint      not null references users (id) on delete cascade,
    rating     smallint    not null check (rating between 1 and 5),
    comment    text        not null default '',
    created_at timestamptz not null default now(),
    unique (product_id, user_id)
);

-- ---------- Wishlist ----------

create table if not exists wishlist (
    user_id    bigint      not null references users (id) on delete cascade,
    product_id bigint      not null references products (id) on delete cascade,
    created_at timestamptz not null default now(),
    primary key (user_id, product_id)
);

-- ---------- Checkout ----------
-- Same as before, plus the customer account and shipping details.

drop function if exists place_order(text, text, jsonb);

create or replace function place_order(p_user_id bigint, p_customer text, p_email text,
                                       p_phone text, p_address text, p_note text, p_items jsonb)
returns bigint
language plpgsql
set search_path = public
as $$
declare
    v_order_id bigint;
    v_total    numeric(10, 2) := 0;
    v_item     record;
    v_product  products%rowtype;
begin
    if coalesce(trim(p_customer), '') = '' or position('@' in coalesce(p_email, '')) = 0 then
        raise exception 'Name and a valid email are required';
    end if;
    if coalesce(trim(p_phone), '') = '' or coalesce(trim(p_address), '') = '' then
        raise exception 'Phone and delivery address are required';
    end if;
    if p_items is null or jsonb_array_length(p_items) = 0 then
        raise exception 'Your cart is empty';
    end if;

    insert into orders (user_id, customer, email, phone, address, note)
    values (p_user_id, trim(p_customer), trim(p_email), trim(p_phone), trim(p_address),
            trim(coalesce(p_note, '')))
    returning id into v_order_id;

    for v_item in
        select (e ->> 'product_id')::bigint as product_id, sum((e ->> 'qty')::int) as qty
        from jsonb_array_elements(p_items) as e
        group by 1
    loop
        if v_item.qty < 1 then
            raise exception 'Quantity must be at least 1';
        end if;

        select * into v_product from products where id = v_item.product_id for update;
        if not found then
            raise exception 'Product #% is no longer available', v_item.product_id;
        end if;
        if v_item.qty > v_product.stock then
            raise exception 'Only % left of "%"', v_product.stock, v_product.name;
        end if;

        insert into order_items (order_id, product_id, name, price, qty)
        values (v_order_id, v_product.id, v_product.name, v_product.price, v_item.qty);
        update products set stock = stock - v_item.qty where id = v_product.id;
        v_total := v_total + v_product.price * v_item.qty;
    end loop;

    update orders set total = v_total where id = v_order_id;
    return v_order_id;
end;
$$;

-- ---------- Order status ----------
-- Cancelling puts the items back in stock. A cancelled order can't be reopened,
-- because its stock may already have been sold again.
-- Returns false when the order doesn't exist.

create or replace function set_order_status(p_order_id bigint, p_status text)
returns boolean
language plpgsql
set search_path = public
as $$
declare
    v_old text;
begin
    select status into v_old from orders where id = p_order_id for update;
    if not found then
        return false;
    end if;
    if v_old = p_status then
        return true;
    end if;
    if v_old = 'cancelled' then
        raise exception 'A cancelled order cannot be reopened';
    end if;
    if p_status = 'cancelled' then
        update products p set stock = p.stock + i.qty
        from order_items i
        where i.order_id = p_order_id and i.product_id = p.id;
    end if;
    update orders set status = p_status where id = p_order_id;
    return true;
end;
$$;
