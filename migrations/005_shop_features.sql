-- Shop settings, coupons, shipping and tax, product galleries and variants,
-- sale prices, order timeline, bank payments, Telegram for customers and
-- password reset.
--
-- Additive only: the old place_order(...7 args) is kept, so code deployed before
-- this migration keeps working until the new code is live.

-- ---------- Shop settings (one row) ----------

create table if not exists shop_settings (
    id                  smallint primary key default 1 check (id = 1),
    shop_name           text           not null default 'WebShop',
    shop_address        text           not null default '',
    shop_phone          text           not null default '',
    shipping_fee        numeric(10, 2) not null default 0 check (shipping_fee >= 0),
    free_shipping_over  numeric(10, 2) not null default 0 check (free_shipping_over >= 0),  -- 0 = never free
    tax_rate            numeric(5, 2)  not null default 0 check (tax_rate between 0 and 100),  -- percent
    low_stock_threshold integer        not null default 5 check (low_stock_threshold >= 0),
    bank_enabled        boolean        not null default false,
    bank_name           text           not null default '',
    bank_account_name   text           not null default '',
    bank_account_number text           not null default '',
    bank_qr_url         text           not null default ''
);

insert into shop_settings (id) values (1) on conflict do nothing;

-- ---------- Coupons ----------

create table if not exists coupons (
    id           bigint generated by default as identity primary key,
    code         text           not null,
    kind         text           not null check (kind in ('percent', 'fixed')),
    value        numeric(10, 2) not null check (value > 0),
    min_subtotal numeric(10, 2) not null default 0 check (min_subtotal >= 0),
    max_uses     integer        check (max_uses > 0),          -- null = unlimited
    used_count   integer        not null default 0 check (used_count >= 0),
    expires_on   date,                                         -- last valid day, Cambodia time
    active       boolean        not null default true,
    created_at   timestamptz    not null default now(),
    check (kind <> 'percent' or value <= 100)
);

create unique index if not exists coupons_code_key on coupons (lower(code));

-- ---------- Products: sale price, featured, gallery, variants ----------

alter table products
    add column if not exists compare_at_price numeric(10, 2) check (compare_at_price >= 0),  -- "was" price
    add column if not exists featured         boolean not null default false,
    add column if not exists images           jsonb   not null default '[]';  -- extra image URLs

create table if not exists product_variants (
    id         bigint generated by default as identity primary key,
    product_id bigint         not null references products (id) on delete cascade,
    name       text           not null,                 -- e.g. "Red / L"
    price      numeric(10, 2) check (price >= 0),       -- null = the product's price
    stock      integer        not null default 0 check (stock >= 0),
    position   integer        not null default 0
);

create index if not exists product_variants_product_idx on product_variants (product_id);

-- Replace a product's variants with p_variants ([{id?, name, price?, stock}]).
-- Rows without an id are added; existing rows not in the list are removed.
-- A product with variants keeps stock = the sum of its variants' stock.
create or replace function save_variants(p_product_id bigint, p_variants jsonb)
returns void
language plpgsql
set search_path = public
as $$
declare
    v_item jsonb;
    v_pos  integer := 0;
    v_keep bigint[] := '{}';
    v_id   bigint;
begin
    for v_item in select * from jsonb_array_elements(coalesce(p_variants, '[]')) loop
        v_pos := v_pos + 1;
        if coalesce(trim(v_item ->> 'name'), '') = '' then
            raise exception 'Every option needs a name';
        end if;
        v_id := nullif(v_item ->> 'id', '')::bigint;
        if v_id is not null then
            update product_variants
               set name = trim(v_item ->> 'name'),
                   price = nullif(v_item ->> 'price', '')::numeric,
                   stock = coalesce(nullif(v_item ->> 'stock', '')::int, 0),
                   position = v_pos
             where id = v_id and product_id = p_product_id
            returning id into v_id;
        end if;
        if v_id is null then
            insert into product_variants (product_id, name, price, stock, position)
            values (p_product_id, trim(v_item ->> 'name'), nullif(v_item ->> 'price', '')::numeric,
                    coalesce(nullif(v_item ->> 'stock', '')::int, 0), v_pos)
            returning id into v_id;
        end if;
        v_keep := v_keep || v_id;
    end loop;

    delete from product_variants where product_id = p_product_id and id <> all (v_keep);

    if v_pos > 0 then
        update products set stock = (select sum(stock) from product_variants where product_id = p_product_id)
         where id = p_product_id;
    end if;
end;
$$;

-- ---------- Orders: charges, coupon, payment, timeline ----------

alter table orders
    add column if not exists subtotal        numeric(10, 2) not null default 0,
    add column if not exists discount        numeric(10, 2) not null default 0,
    add column if not exists shipping_fee    numeric(10, 2) not null default 0,
    add column if not exists tax             numeric(10, 2) not null default 0,
    add column if not exists coupon_id       bigint references coupons (id) on delete set null,
    add column if not exists coupon_code     text not null default '',
    add column if not exists payment_method  text not null default 'cod'
                                             check (payment_method in ('cod', 'bank')),
    add column if not exists payment_status  text not null default 'unpaid'
                                             check (payment_status in ('unpaid', 'submitted', 'paid')),
    add column if not exists payment_proof   text not null default '';  -- storage key of the screenshot

-- Orders placed before this migration had no extra charges.
update orders set subtotal = total where subtotal = 0 and total > 0;
update orders set payment_status = 'paid' where status = 'delivered' and payment_status = 'unpaid';

alter table order_items
    add column if not exists variant_id bigint references product_variants (id) on delete set null;

create table if not exists order_events (
    id         bigint generated by default as identity primary key,
    order_id   bigint      not null references orders (id) on delete cascade,
    event      text        not null,   -- placed, shipped, delivered, cancelled, payment ...
    note       text        not null default '',
    created_at timestamptz not null default now()
);

create index if not exists order_events_order_idx on order_events (order_id);

insert into order_events (order_id, event, created_at)
select o.id, 'placed', o.created_at from orders o
where not exists (select 1 from order_events e where e.order_id = o.id);

-- ---------- Charges: coupon discount, shipping and tax for a subtotal ----------
-- Raises a readable error when the coupon can't be used.

create or replace function order_charges(p_subtotal numeric, p_coupon text,
                                         out coupon_id bigint, out coupon_code text,
                                         out discount numeric, out shipping numeric, out tax numeric)
language plpgsql
set search_path = public
as $$
declare
    c coupons%rowtype;
    s shop_settings%rowtype;
    v_after numeric;
begin
    discount := 0;
    coupon_code := '';
    if coalesce(trim(p_coupon), '') <> '' then
        select * into c from coupons where lower(code) = lower(trim(p_coupon));
        if not found or not c.active then
            raise exception 'Coupon "%" is not valid', trim(p_coupon);
        end if;
        if c.expires_on is not null and c.expires_on < (now() at time zone 'Asia/Phnom_Penh')::date then
            raise exception 'Coupon "%" has expired', c.code;
        end if;
        if c.max_uses is not null and c.used_count >= c.max_uses then
            raise exception 'Coupon "%" has been used up', c.code;
        end if;
        if p_subtotal < c.min_subtotal then
            raise exception 'Coupon "%" needs a subtotal of at least $%', c.code, c.min_subtotal;
        end if;
        coupon_id := c.id;
        coupon_code := c.code;
        discount := case when c.kind = 'percent' then round(p_subtotal * c.value / 100, 2)
                         else least(c.value, p_subtotal) end;
    end if;

    select * into s from shop_settings where id = 1;
    v_after := p_subtotal - discount;
    shipping := case when p_subtotal = 0 then 0
                     when s.free_shipping_over > 0 and v_after >= s.free_shipping_over then 0
                     else s.shipping_fee end;
    tax := round(v_after * s.tax_rate / 100, 2);
end;
$$;

-- ---------- Price a cart without placing it (for the checkout summary) ----------

create or replace function quote_order(p_items jsonb, p_coupon text)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
    v_subtotal numeric := 0;
    v_item     record;
    v_charges  record;
begin
    for v_item in
        select (e ->> 'qty')::int as qty, coalesce(v.price, p.price) as price
        from jsonb_array_elements(coalesce(p_items, '[]')) as e
        join products p on p.id = (e ->> 'product_id')::bigint
        left join product_variants v on v.id = nullif(e ->> 'variant_id', '')::bigint
                                    and v.product_id = p.id
    loop
        v_subtotal := v_subtotal + v_item.price * greatest(v_item.qty, 0);
    end loop;

    select * into v_charges from order_charges(v_subtotal, p_coupon);
    return jsonb_build_object(
        'subtotal', v_subtotal, 'discount', v_charges.discount, 'shipping_fee', v_charges.shipping,
        'tax', v_charges.tax, 'coupon_code', v_charges.coupon_code,
        'total', v_subtotal - v_charges.discount + v_charges.shipping + v_charges.tax);
end;
$$;

-- ---------- Checkout ----------
-- Same as before, plus variants, coupon, shipping, tax and payment method.
-- p_items: [{product_id, variant_id?, qty}]

create or replace function place_order(p_user_id bigint, p_customer text, p_email text,
                                       p_phone text, p_address text, p_note text, p_items jsonb,
                                       p_coupon text, p_payment_method text)
returns bigint
language plpgsql
set search_path = public
as $$
declare
    v_order_id bigint;
    v_subtotal numeric(10, 2) := 0;
    v_item     record;
    v_product  products%rowtype;
    v_variant  product_variants%rowtype;
    v_price    numeric(10, 2);
    v_name     text;
    v_charges  record;
begin
    if coalesce(trim(p_customer), '') = '' or position('@' in coalesce(p_email, '')) = 0 then
        raise exception 'Name and a valid email are required';
    end if;
    if coalesce(trim(p_phone), '') = '' or coalesce(trim(p_address), '') = '' then
        raise exception 'Phone and delivery address are required';
    end if;
    if p_items is null or jsonb_array_length(p_items) = 0 then
        raise exception 'Your cart is empty';
    end if;
    if p_payment_method not in ('cod', 'bank') then
        raise exception 'Choose a payment method';
    end if;
    if p_payment_method = 'bank' and not (select bank_enabled from shop_settings where id = 1) then
        raise exception 'Bank transfer is not available right now';
    end if;

    insert into orders (user_id, customer, email, phone, address, note, payment_method)
    values (p_user_id, trim(p_customer), trim(p_email), trim(p_phone), trim(p_address),
            trim(coalesce(p_note, '')), p_payment_method)
    returning id into v_order_id;

    for v_item in
        select (e ->> 'product_id')::bigint as product_id,
               nullif(e ->> 'variant_id', '')::bigint as variant_id,
               sum((e ->> 'qty')::int) as qty
        from jsonb_array_elements(p_items) as e
        group by 1, 2
    loop
        if v_item.qty < 1 then
            raise exception 'Quantity must be at least 1';
        end if;

        select * into v_product from products where id = v_item.product_id for update;
        if not found then
            raise exception 'Product #% is no longer available', v_item.product_id;
        end if;

        if v_item.variant_id is null then
            if exists (select 1 from product_variants where product_id = v_product.id) then
                raise exception 'Choose an option for "%"', v_product.name;
            end if;
            if v_item.qty > v_product.stock then
                raise exception 'Only % left of "%"', v_product.stock, v_product.name;
            end if;
            v_price := v_product.price;
            v_name := v_product.name;
        else
            select * into v_variant from product_variants
             where id = v_item.variant_id and product_id = v_product.id for update;
            if not found then
                raise exception 'An option of "%" is no longer available', v_product.name;
            end if;
            if v_item.qty > v_variant.stock then
                raise exception 'Only % left of "% (%)"', v_variant.stock, v_product.name, v_variant.name;
            end if;
            update product_variants set stock = stock - v_item.qty where id = v_variant.id;
            v_price := coalesce(v_variant.price, v_product.price);
            v_name := v_product.name || ' (' || v_variant.name || ')';
        end if;

        insert into order_items (order_id, product_id, variant_id, name, price, qty)
        values (v_order_id, v_product.id, v_item.variant_id, v_name, v_price, v_item.qty);
        update products set stock = stock - v_item.qty where id = v_product.id;
        v_subtotal := v_subtotal + v_price * v_item.qty;
    end loop;

    select * into v_charges from order_charges(v_subtotal, p_coupon);
    if v_charges.coupon_id is not null then
        -- Counted here, under a row lock, so a limited coupon can't be overused.
        update coupons set used_count = used_count + 1
         where id = v_charges.coupon_id and (max_uses is null or used_count < max_uses);
        if not found then
            raise exception 'Coupon "%" has been used up', v_charges.coupon_code;
        end if;
    end if;

    update orders
       set subtotal = v_subtotal, discount = v_charges.discount, shipping_fee = v_charges.shipping,
           tax = v_charges.tax, coupon_id = v_charges.coupon_id, coupon_code = v_charges.coupon_code,
           total = v_subtotal - v_charges.discount + v_charges.shipping + v_charges.tax
     where id = v_order_id;
    insert into order_events (order_id, event) values (v_order_id, 'placed');
    return v_order_id;
end;
$$;

-- ---------- Order status ----------
-- As before, plus: variants are restocked, the coupon use is given back,
-- a cash-on-delivery order counts as paid once delivered, and every change
-- is added to the timeline.

create or replace function set_order_status(p_order_id bigint, p_status text)
returns boolean
language plpgsql
set search_path = public
as $$
declare
    v_order orders%rowtype;
begin
    select * into v_order from orders where id = p_order_id for update;
    if not found then
        return false;
    end if;
    if v_order.status = p_status then
        return true;
    end if;
    if v_order.status = 'cancelled' then
        raise exception 'A cancelled order cannot be reopened';
    end if;
    if p_status = 'cancelled' then
        update products p set stock = p.stock + i.qty
          from order_items i
         where i.order_id = p_order_id and i.product_id = p.id;
        update product_variants v set stock = v.stock + i.qty
          from order_items i
         where i.order_id = p_order_id and i.variant_id = v.id;
        if v_order.coupon_id is not null then
            update coupons set used_count = greatest(used_count - 1, 0) where id = v_order.coupon_id;
        end if;
    end if;
    update orders
       set status = p_status,
           payment_status = case when p_status = 'delivered' and payment_method = 'cod' then 'paid'
                                 else payment_status end
     where id = p_order_id;
    insert into order_events (order_id, event) values (p_order_id, p_status);
    return true;
end;
$$;

