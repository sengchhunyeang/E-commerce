-- ---------- Tables ----------

create table if not exists products (
    id          bigint generated by default as identity primary key,
    name        text           not null,
    price       numeric(10, 2) not null check (price >= 0),
    stock       integer        not null default 0 check (stock >= 0),
    image_url   text           not null default '',
    description text           not null default '',
    created_at  timestamptz    not null default now()
);

create table if not exists orders (
    id         bigint generated by default as identity primary key,
    customer   text           not null,
    email      text           not null,
    total      numeric(10, 2) not null default 0,
    status     text           not null default 'pending'
               check (status in ('pending', 'shipped', 'delivered', 'cancelled')),
    created_at timestamptz    not null default now()
);

create table if not exists order_items (
    id         bigint generated by default as identity primary key,
    order_id   bigint         not null references orders (id) on delete cascade,
    product_id bigint         references products (id) on delete set null,
    name       text           not null,
    price      numeric(10, 2) not null,
    qty        integer        not null check (qty > 0)
);

-- ---------- Checkout ----------
-- Places an order in one transaction: checks stock, saves the items,
-- lowers stock and sets the total. Any error rolls everything back.

create or replace function place_order(p_customer text, p_email text, p_items jsonb)
returns bigint
language plpgsql
set search_path = public
as $$
declare
    v_order_id bigint;
    v_total    numeric(10, 2) := 0;
    v_item     record;
    v_product  products%rowtype;
begin
    if coalesce(trim(p_customer), '') = '' or position('@' in coalesce(p_email, '')) = 0 then
        raise exception 'Name and a valid email are required';
    end if;
    if p_items is null or jsonb_array_length(p_items) = 0 then
        raise exception 'Your cart is empty';
    end if;

    insert into orders (customer, email) values (trim(p_customer), trim(p_email))
    returning id into v_order_id;

    for v_item in
        select (e ->> 'product_id')::bigint as product_id, sum((e ->> 'qty')::int) as qty
        from jsonb_array_elements(p_items) as e
        group by 1
    loop
        if v_item.qty < 1 then
            raise exception 'Quantity must be at least 1';
        end if;

        select * into v_product from products where id = v_item.product_id for update;
        if not found then
            raise exception 'Product #% is no longer available', v_item.product_id;
        end if;
        if v_item.qty > v_product.stock then
            raise exception 'Only % left of "%"', v_product.stock, v_product.name;
        end if;

        insert into order_items (order_id, product_id, name, price, qty)
        values (v_order_id, v_product.id, v_product.name, v_product.price, v_item.qty);
        update products set stock = stock - v_item.qty where id = v_product.id;
        v_total := v_total + v_product.price * v_item.qty;
    end loop;

    update orders set total = v_total where id = v_order_id;
    return v_order_id;
end;
$$;

